#!/usr/bin/env python3
"""Builds games/room/plan.js (the illustrated floor plan for Room for Everyone) from tour/model.json.
Run from the repo root:  python3 games/room/build_plan.py
Units are feet in the tour's world frame (x east, z south; the street is at +z)."""
import json, pathlib
from shapely.geometry import box
from shapely.ops import unary_union

ROOT = pathlib.Path(__file__).resolve().parents[2]
M = json.loads((ROOT / "tour/model.json").read_text())
C, R = M["collide"], M["rooms"]
W, H, CELL, X0, Z0 = C["w"], C["h"], C["cell"], C["x0"], C["z0"]
IDS = R["ids"]
wp = lambda px, py: ((px - 1300) / 26.8, (py - 1900) / 26.8)   # plan pixels -> feet (ppf 26.8, origin 1300,1900)

def cells(level):
    out = {}
    for i, ch in enumerate(R[level]):
        if ch == ".": continue
        x, z = X0 + (i % W) * CELL, Z0 + (i // W) * CELL
        out.setdefault(IDS[ord(ch) - 48], []).append(box(x, z, x + CELL, z + CELL))
    return out

def shape(boxes):
    g = unary_union(boxes).buffer(.05, join_style=2).buffer(-.05, join_style=2)
    return g.simplify(.12, preserve_topology=True)

def path(g):
    polys = [g] if g.geom_type == "Polygon" else list(g.geoms)
    d = []
    for p in polys:
        if p.area < 4: continue
        for ring in [p.exterior] + list(p.interiors):
            pts = list(ring.coords)[:-1]
            d.append("M" + "L".join(f"{x:.2f},{z:.2f}" for x, z in pts) + "Z")
    return "".join(d)

def split(g, fn):
    a = unary_union([b for b in g if fn(b.centroid.x, b.centroid.y)]); r = unary_union([b for b in g if not fn(b.centroid.x, b.centroid.y)])
    return a, r

plan = {"levels": {}}
# ---- ground plan: the lower level, the garage and the main level are drawn together (split level) ----
c = cells("main")
kitchen_cells = c.pop("kitchen")
c["kitchen"] = [b for b in kitchen_cells if b.centroid.y < 15.3]
c["great"] = [b for b in kitchen_cells if b.centroid.y >= 15.3]
lb = c.pop("lbed1")
c["lbed1"] = [b for b in lb if b.centroid.y < -37.3]
c["lbath"] = [b for b in lb if b.centroid.y >= -37.3]
up = cells("upper")
for lvl, cs in (("ground", c), ("upper", up)):
    rooms = {}
    for rid, bx in cs.items():
        if not bx: continue
        g = shape(bx); rp = g.representative_point()
        rooms[rid] = {"d": path(g), "c": [round(rp.x, 2), round(rp.y, 2)], "area": round(g.area)}
    src = "main" if lvl == "ground" else "upper"
    walls = [[round(min(w[0], w[2]), 2), round(min(w[1], w[3]), 2), round(abs(w[2] - w[0]), 2), round(abs(w[3] - w[1]), 2)] for w in M["walls"] if w[7] == src]
    glass = [[round(min(g[0], g[2]), 2), round(min(g[1], g[3]), 2), round(abs(g[2] - g[0]), 2), round(abs(g[3] - g[1]), 2), g[6]] for g in M["glass"] if g[7] == src]
    allg = unary_union([shape(b) for b in cs.values() if b] + [box(w[0], w[1], w[0] + w[2], w[1] + w[3]) for w in walls])
    x0, z0, x1, z1 = allg.bounds
    geo = {rid: shape(bx) for rid, bx in cs.items() if bx}
    adj = sorted({tuple(sorted((a, b))) for a in geo for b in geo if a < b and geo[a].buffer(.45).intersection(geo[b].buffer(.45)).length > 3})
    plan.setdefault("adjacent", []).extend([list(t) for t in adj])
    plan["levels"][lvl] = {"rooms": rooms, "walls": walls, "glass": glass, "bounds": [round(x0 - 2, 1), round(z0 - 2, 1), round(x1 + 2, 1), round(z1 + 2, 1)]}

# label anchors from the tour's room list (plan pixels), where the tour has them
AT = {"frontdeck": (1220, 2150), "garage": (822, 2200), "entry": (1160, 1835), "living": (1480, 1830), "kitchen": (1640, 2160), "great": (1590, 2600),
      "mainbath": (2065, 2160), "stairs": (960, 1700), "rec": (855, 1390), "lbed1": (865, 740), "lbed2": (610, 1000), "office": (585, 1710),
      "lbath": (945, 1050), "laundry": (555, 1385)}
for rid, (px, py) in AT.items():
    r = plan["levels"]["ground"]["rooms"].get(rid)
    if r: r["at"] = [round(v, 2) for v in wp(px, py)]
plan["levels"]["ground"]["streetSide"] = "+z"
out = ROOT / "games/room/plan.js"
out.write_text("/* generated by build_plan.py from tour/model.json - do not edit by hand */\nwindow.PLAN = " + json.dumps(plan, separators=(",", ":")) + ";\n")
print(out, out.stat().st_size, {k: sorted(v["rooms"]) for k, v in plan["levels"].items()}, {k: v["bounds"] for k, v in plan["levels"].items()})
